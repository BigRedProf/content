using BigRedProf.Content.Core;
using BigRedProf.Content.Core.Data;
using BigRedProf.Content.Core.PackRats;
using BigRedProf.Content.Core.Providers;
using BigRedProf.Data.Core;
using BigRedProf.Stories;
using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Text;
using System.Threading.Tasks;

namespace BigRedProf.Content.Golden
{
	/// <summary>
	/// Captures golden bytes from the pre-BitStream content store.
	/// This program is the capture tool for <c>golden.txt</c>. It is not part of
	/// <c>Content.sln</c>. Run it from this directory before any BitStream change:
	/// <c>dotnet run -- golden.txt</c>.
	/// </summary>
	internal static class GenerateGoldenBytes
	{
		#region functions
		private static int Main(string[] args)
		{
			string outputPath = args.Length > 0 ? args[0] : "golden.txt";

			StringBuilder manifest = new StringBuilder();
			manifest.AppendLine("# Golden bytes captured from the content store before the BitStream change.");
			manifest.AppendLine("# Generated by src/Golden/GenerateGoldenBytes.cs against pre-BitStream main.");
			manifest.AppendLine("# Do not edit. Any later diff to this file fails review.");
			manifest.AppendLine("#");
			manifest.AppendLine("# Each sample is one code the store persists: the blob bytes, the multihash");
			manifest.AppendLine("# id, the shard directory, the ContentStored encoding, and the catalog datum.");
			manifest.AppendLine();

			WriteSample(
				manifest,
				"content-byte-aligned",
				new Code(new byte[] { 0x42, 0x49, 0x47, 0x52, 0x45, 0x44 }),
				new string[0]
			);
			WriteSample(
				manifest,
				"content-mid-byte",
				new Code("101"),
				new string[0]
			);
			WriteSample(
				manifest,
				"content-zero-bit",
				new Code(0),
				new string[0]
			);
			WriteSample(
				manifest,
				"content-back-to-back",
				new Code("101" + "01011" + "1" + "1111000"),
				new string[]
				{
					"WRITE 101",
					"WRITE 01011",
					"WRITE -",
					"WRITE 1",
					"WRITE 1111000"
				}
			);

			File.WriteAllText(outputPath, manifest.ToString().Replace("\r\n", "\n"));
			Console.WriteLine("Wrote " + outputPath);
			return 0;
		}

		private static void WriteSample(StringBuilder manifest, string name, Code content, string[] operations)
		{
			if(name == "content-mid-byte" && (content.Length % 8) == 0)
				throw new InvalidOperationException(name + " must end partway through a byte.");

			if(name == "content-zero-bit" && content.Length != 0)
				throw new InvalidOperationException(name + " must be a 0-bit code.");

			string bits = ToBits(content);
			Code rebuilt = bits == "-" ? new Code(0) : new Code(bits);
			if(rebuilt != content)
				throw new InvalidOperationException(name + " bit string does not round-trip.");

			if(operations.Length > 0)
			{
				string concatenated = ConcatenateOperations(operations);
				if(concatenated != bits)
					throw new InvalidOperationException(name + " operations are not the stored bits.");
			}

			PiedPiper piedPiper = CreatePiedPiper();
			byte[] blob = piedPiper.SaveCodeToByteArray(content);
			Code loaded = piedPiper.LoadCodeFromByteArray(blob);
			if(loaded != content)
				throw new InvalidOperationException(name + " blob does not round-trip.");

			Multihash multihash = Multihash.FromCode(content, ContentStore.DefaultAlgorithm);
			string id = multihash.ToMultibaseString();

			ContentStored model = new ContentStored()
			{
				Multihash = multihash
			};
			Code stored = piedPiper.PackModel<ContentStored>(model, ContentSchemaId.ContentStored);
			ContentStored unpackedStored = piedPiper.UnpackModel<ContentStored>(stored, ContentSchemaId.ContentStored);
			if(unpackedStored.Multihash != multihash)
				throw new InvalidOperationException(name + " ContentStored encoding does not round-trip.");

			Datum datum = piedPiper.PackDatum(model, ContentSchemaId.ContentStored);
			Code catalog = piedPiper.PackModel<Datum>(datum, CoreSchema.Datum);

			string root = Path.Combine(Path.GetTempPath(), "BigRedProf.Content.Golden", name);
			if(Directory.Exists(root))
				Directory.Delete(root, true);

			string shard;
			string relativePath;
			byte[] storedBlob;
			Code recorded;
			try
			{
				RecordingScribe scribe = new RecordingScribe();
				ContentStore store = new ContentStore(new DiskContentStoreStorageProvider(root), scribe);
				store.PutContentAsync(content).GetAwaiter().GetResult();

				if(scribe.Things.Count != 1)
					throw new InvalidOperationException(name + " did not record one catalog code.");

				recorded = scribe.Things[0];
				if(recorded != catalog)
					throw new InvalidOperationException(name + " catalog code does not match the store.");

				storedBlob = ReadSingleBlob(root, out shard, out string fileName);
				if(fileName != id)
					throw new InvalidOperationException(name + " blob file name is not the multihash id.");

				relativePath = "blobs/" + shard + "/" + id;
			}
			finally
			{
				if(Directory.Exists(root))
					Directory.Delete(root, true);
			}

			if(!BytesEqual(storedBlob, blob))
				throw new InvalidOperationException(name + " disk blob does not match SaveCodeToByteArray.");

			manifest.AppendLine("SAMPLE " + name);
			manifest.AppendLine("KIND stored-content");
			foreach(string operation in operations)
				manifest.AppendLine("OP " + operation);
			manifest.AppendLine("BITS " + bits);
			manifest.AppendLine("BIT_LENGTH " + content.Length.ToString(CultureInfo.InvariantCulture));
			manifest.AppendLine("BLOB_HEX " + ToHex(blob));
			manifest.AppendLine("ID " + id);
			manifest.AppendLine("SHARD " + shard);
			manifest.AppendLine("PATH " + relativePath);
			manifest.AppendLine("STORED_BIT_LENGTH " + stored.Length.ToString(CultureInfo.InvariantCulture));
			manifest.AppendLine("STORED_HEX " + ToHex(stored.ToByteArray()));
			manifest.AppendLine("CATALOG_BIT_LENGTH " + catalog.Length.ToString(CultureInfo.InvariantCulture));
			manifest.AppendLine("CATALOG_HEX " + ToHex(catalog.ToByteArray()));
			manifest.AppendLine("END");
			manifest.AppendLine();
		}

		private static PiedPiper CreatePiedPiper()
		{
			PiedPiper piedPiper = new PiedPiper();
			piedPiper.RegisterCorePackRats();
			piedPiper.RegisterPackRat<ContentStored>(
				new ContentStoredPackRat(piedPiper),
				ContentSchemaId.ContentStored
			);
			return piedPiper;
		}

		private static string ConcatenateOperations(string[] operations)
		{
			StringBuilder builder = new StringBuilder();
			foreach(string operation in operations)
			{
				if(!operation.StartsWith("WRITE ", StringComparison.Ordinal))
					throw new InvalidOperationException("Content samples only write. Got '" + operation + "'.");

				string written = operation.Substring("WRITE ".Length);
				if(written == "-")
					continue;

				builder.Append(written);
			}

			string bits = builder.ToString();
			if(bits.Length == 0)
				return "-";

			return bits;
		}

		private static string ToBits(Code code)
		{
			if(code.Length == 0)
				return "-";

			char[] chars = new char[code.Length];
			for(int i = 0; i < code.Length; ++i)
				chars[i] = code[i] == 0 ? '0' : '1';

			return new string(chars);
		}

		private static byte[] ReadSingleBlob(string root, out string shard, out string fileName)
		{
			string blobsDirectory = Path.Combine(root, "blobs");
			string[] shardDirectories = Directory.GetDirectories(blobsDirectory);
			if(shardDirectories.Length != 1)
				throw new InvalidOperationException("Expected one shard directory.");

			shard = Path.GetFileName(shardDirectories[0]);
			string[] files = Directory.GetFiles(shardDirectories[0]);
			if(files.Length != 1)
				throw new InvalidOperationException("Expected one blob file.");

			fileName = Path.GetFileName(files[0]);
			return File.ReadAllBytes(files[0]);
		}

		private static bool BytesEqual(byte[] left, byte[] right)
		{
			if(left.Length != right.Length)
				return false;

			for(int i = 0; i < left.Length; ++i)
			{
				if(left[i] != right[i])
					return false;
			}

			return true;
		}

		private static string ToHex(byte[] bytes)
		{
			if(bytes.Length == 0)
				return "-";

			StringBuilder builder = new StringBuilder(bytes.Length * 2);
			for(int i = 0; i < bytes.Length; ++i)
				builder.Append(bytes[i].ToString("x2", CultureInfo.InvariantCulture));

			return builder.ToString();
		}
		#endregion

		#region nested types
		private sealed class RecordingScribe : IScribe
		{
			#region fields
			private readonly List<Code> _things;
			#endregion

			#region constructors
			public RecordingScribe()
			{
				_things = new List<Code>();
			}
			#endregion

			#region properties
			public IReadOnlyList<Code> Things
			{
				get
				{
					return _things;
				}
			}
			#endregion

			#region IScribe methods
			public void RecordSomething(params Code[] things)
			{
				Task task = RecordSomethingAsync(things);
				task.Wait();
			}

			public Task RecordSomethingAsync(params Code[] things)
			{
				if(things == null)
					throw new ArgumentNullException(nameof(things));

				_things.AddRange(things);
				return Task.CompletedTask;
			}
			#endregion
		}
		#endregion
	}
}
